"""Generate docs/COMMAND_REFERENCE.md from the `rkb` argument parser: every command with its options, so the reference cannot drift
from the code.

Usage: python -I tools/s12_command_reference.py [--check]      (--check exits 1 if the Markdown is out of date)
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src")]

GROUPS = {"init": "KB lifecycle", "doctor": "KB lifecycle", "backup": "KB lifecycle", "verify-backup": "KB lifecycle", "restore": "KB lifecycle",
          "upgrade": "KB lifecycle", "reconcile": "KB lifecycle", "metadata": "S02 metadata", "integrity": "S02 publication integrity",
          "index": "S02 / S09 indexes", "import-reprovane": "S02 Reprovane import", "library": "S03 global library", "asset": "S03 assets",
          "rights": "S03 rights", "bridge": "S04 download bridge", "journal": "S04J journal harvesting", "fte": "S05 full-text eligibility",
          "parse": "S06 PDF parsing", "screen": "S07 AI screening proposals", "evidence": "S08 evidence extraction", "retrieval": "S09 retrieval",
          "search": "S09 retrieval", "rag": "S09 retrieval", "passage": "S09 retrieval", "ai": "S10 AI integration gateway", "synth": "S11 synthesis and citation audit",
          "llm": "LLM provider routing (ADR_LLM; L1 offline, L2 loopback-only local models)"}


def leaves(parser, prefix):
    subs = [a for a in parser._actions if a.__class__.__name__ == "_SubParsersAction"]
    if not subs:
        yield " ".join(prefix), parser
        return
    for name, sp in subs[0].choices.items():
        yield from leaves(sp, prefix + [name])


def option_text(action):
    if action.option_strings:
        flag = " / ".join(action.option_strings)
        if action.nargs == 0:
            return f"`{flag}`"
        return f"`{flag} {action.metavar or action.dest.upper()}`"
    return f"`{action.metavar or action.dest}`"


def render() -> str:
    from scivetra_kb import __version__, cli
    parser = cli._parser()
    out = [f"# `rkb` command reference ({__version__})", "",
           "Generated by `tools/s12_command_reference.py` from the argument parser; do not edit by hand. Every command prints one JSON",
           "document. Workflows and safety rules are in `SCIVETRA_USER_MANUAL.md` and the stage guides.", ""]
    current = None
    for name, sp in sorted(leaves(parser, ["rkb"]), key=lambda x: (list(GROUPS).index(x[0].split()[1]) if x[0].split()[1] in GROUPS else 99, x[0])):
        group = GROUPS.get(name.split()[1], "Other")
        if group != current:
            out += [f"## {group}", "", "| Command | Required | Optional |", "|---|---|---|"]
            current = group
        acts = [a for a in sp._actions if a.dest != "help" and a.__class__.__name__ != "_SubParsersAction"]
        req = ", ".join(option_text(a) for a in acts if a.required or not a.option_strings) or "-"
        opt = ", ".join(option_text(a) for a in acts if not a.required and a.option_strings) or "-"
        out.append(f"| `{name}` | {req.replace('|', '/')} | {opt.replace('|', '/')} |")
    text = "\n".join(out)
    return "\n\n## ".join(part.rstrip() for part in text.split("\n## ")) + "\n"


def main(argv):
    target = ROOT / "docs" / "COMMAND_REFERENCE.md"
    md = render()
    if "--check" in argv:
        ok = target.is_file() and target.read_text(encoding="utf-8") == md
        print({"ok": ok})
        return 0 if ok else 1
    target.write_text(md, encoding="utf-8", newline="\n")
    print({"commands": md.count("\n| `rkb ")})
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
