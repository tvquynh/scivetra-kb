"""Build the S11 scenario catalogue from the S11 test docstrings (``IDs: S11-...``).

Usage: python -I tools/s11_scenario_catalogue.py [--json OUT.json] [--check]
Every scenario id maps to the test(s) that exercise it; ``--check`` exits 1 if the Markdown is out of date. The >= 120 claim cases
of the synthetic scientific evaluation are separate (tools/s11_evaluation.py).
"""
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ID = re.compile(r"S11-[A-Z0-9]+(?:[-.][A-Z0-9]+)*")
SCENARIO = re.compile(r"^S11-")


def collect():
    out = {}
    for path in sorted((ROOT / "tests").glob("test_s11_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for cls in [n for n in tree.body if isinstance(n, ast.ClassDef)]:
            for fn in [n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name.startswith("test_")]:
                doc = ast.get_docstring(fn) or ""
                head, _, summary = doc.partition(".")
                for i in ID.findall(head):
                    out.setdefault(i, []).append({"test": f"{path.stem}.{cls.name}.{fn.name}", "summary": " ".join(doc.split())[:400]})
    return dict(sorted(out.items(), key=lambda kv: [int(p) if p.isdigit() else p for p in re.split(r"(\d+)", kv[0])]))


def markdown(ids) -> str:
    scen = [i for i in ids if SCENARIO.match(i)]
    lines = ["# S11 scenario catalogue (generated by tools/s11_scenario_catalogue.py; do not edit)", "",
             f"{len(scen)} distinct S11 test scenario ids. Every scenario is synthetic and offline. Positive (SUPPORTED, human-reviewed, "
             "exported) and negative (abstaining, denied) paths are separate tests, so a deny-everything implementation fails. The 244 "
             "claim cases of the scientific evaluation are listed in evidence/s11_evaluation/.", "", "| Id | Test | What it proves |", "|---|---|---|"]
    for i, tests in ids.items():
        for t in tests:
            lines.append(f"| {i} | `{t['test']}` | {t['summary'].replace('|', '/')} |")
    return "\n".join(lines) + "\n"


def main(argv):
    ids = collect()
    md = markdown(ids)
    target = ROOT / "docs" / "S11_SCENARIO_CATALOGUE.md"
    scen = [i for i in ids if SCENARIO.match(i)]
    if "--json" in argv:
        Path(argv[argv.index("--json") + 1]).write_text(json.dumps({"scenarios": len(scen), "ids": ids}, indent=1) + "\n", encoding="utf-8")
    if "--check" in argv:
        ok = target.is_file() and target.read_text(encoding="utf-8") == md and len(scen) >= 60
        print(json.dumps({"scenarios": len(scen), "catalogue_current": ok}))
        return 0 if ok else 1
    target.write_text(md, encoding="utf-8", newline="\n")
    print(json.dumps({"scenarios": len(scen), "ids": len(ids)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
