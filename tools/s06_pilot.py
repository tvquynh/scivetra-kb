"""S06 bounded synthetic parsing pilot: 100 generated PDFs through G1 v2 intake, gates and the parser sandbox, built twice.

Every PDF is generated by tests/s06_pdf_fixtures.py (no real document, no provider call). Accounting separates:
syntactic acceptance (intake G1 v2), the parse gates (identity / rights), parse outcome and status, and the identity state
the S03 title-page check assigned (identity correctness is a HUMAN decision; the pilot confirms links as a simulated human).
Usage: python -I tools/s06_pilot.py --out-dir DIR   (needs the pinned pypdf; on Windows the language-level guard is accepted)
"""
import argparse
import csv
import hashlib
import io
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "src"), str(ROOT)]

from tests import s06_pdf_fixtures as F  # noqa: E402
from tests.s06_helpers import S06Case  # noqa: E402


def plan():
    """(family, paper_index, bytes, scenario) for exactly 100 documents."""
    docs = []

    def body(i, family):
        return [f"Synthetic results paragraph for document {i} ({family}).", "Methods: a synthetic protocol was followed."]

    i = 0
    for family in ("classic", "xref_stream", "object_stream"):
        for _ in range(20):
            pages = [F.text_page(title_lines(i, body(i, family))), F.text_page([f"Second page of document {i}."])]
            docs.append((family, i, F.build_pdf(pages, syntax=family), "PARSE_RESEARCH"))
            i += 1
    for k in range(8):
        base, upd = ("classic", "classic") if k < 4 else ("object_stream", "xref_stream")
        docs.append((f"incremental_{upd}", i, F.incremental_update([F.text_page(title_lines(i, body(i, "inc")))], F.text_page([f"Erratum page {i}."]),
                                                                   base_syntax=base, syntax=upd), "PARSE_RESEARCH"))
        i += 1
    for k in range(8):
        pages = [F.text_page(title_lines(i, body(i, "mixed"))), F.formula_page("Estimator", "∑ x² ≤ α"),
                 F.two_column_page([f"left {k} a", f"left {k} b"], [f"right {k} a", f"right {k} b"]),
                 F.table_page("Table", [["g", "n", "m"], ["A", str(k), "1.0"], ["B", "2", "3.5"]]), F.scanned_page()]
        docs.append(("mixed_layout", i, F.build_pdf(pages, syntax="object_stream"), "PARSE_RESEARCH"))
        i += 1
    for k in range(6):
        docs.append(("scanned_only", i, F.build_pdf([F.scanned_page()] * (1 + k % 3), syntax="xref_stream", info={"Title": f"scan {i}"}),
                     "PARSE_RESEARCH"))
        i += 1
    good = F.build_pdf([F.text_page(title_lines(i, ["negative base"]))], syntax="xref_stream")
    for name, data in (("html_challenge", b"<!DOCTYPE html><html><body>verify you are human</body></html>\n"), ("truncated", F.truncated(good)),
                       ("encrypted", F.build_pdf([F.text_page(["x"])], encrypt=True, syntax="xref_stream")), ("corrupt_xref_stream", F.corrupt_xref_stream(good)),
                       ("wrong_startxref", F.wrong_startxref(good)), ("no_eof", F.no_eof(good))):
        docs.append((f"negative_{name}", i, data, "INTAKE_REJECT"))
        i += 1
    for _ in range(4):
        docs.append(("object_stream", i, F.build_pdf([F.text_page(title_lines(i, ["rights unknown"]))], syntax="object_stream"), "RIGHTS_UNKNOWN"))
        i += 1
    for _ in range(4):
        docs.append(("xref_stream", i, F.build_pdf([F.text_page(title_lines(i, ["unconfirmed identity"]))], syntax="xref_stream"), "IDENTITY_INSPECTION"))
        i += 1
    for _ in range(4):
        docs.append(("operator_flood", i, F.operator_flood(180_000 + i), "PARSE_TIMEOUT"))  # distinct bytes per paper
        i += 1
    assert len(docs) == 100
    return docs


def title_lines(i, body):
    return [f"Synthetic parsing paper {i}", "First Synthetic, Second Synthetic", f"https://doi.org/10.99999/s06.{i}"] + list(body)


class Pilot(S06Case):
    N_PAPERS = 100

    def runTest(self):
        pass


def build():
    case = Pilot()
    case.setUp()
    try:
        rows = []
        for family, i, data, scenario in plan():
            confirm = scenario != "IDENTITY_INSPECTION"
            rights = None if scenario == "RIGHTS_UNKNOWN" else "OPEN"
            reg = case.register(f"doc_{i:03d}.pdf", data, paper=i, confirm=confirm, rights=rights)
            row = {"doc": i, "family": family, "scenario": scenario, "fixture_sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data),
                   "intake": reg["outcome"], "intake_reasons": reg.get("reasons", []), "identity_state_auto": reg.get("identity_state")}
            if reg["outcome"] == "REGISTERED":
                purpose = "IDENTITY_INSPECTION" if scenario == "IDENTITY_INSPECTION" else "RESEARCH_PARSE"
                limits = {"timeout_seconds": 1} if scenario == "PARSE_TIMEOUT" else None
                out = case.parse(reg["asset_sha256"], reg["link_id"], purpose, limits=limits)
                row.update(purpose=purpose, parse=out["outcome"], parse_reasons=out.get("reasons", []), status=out.get("status"),
                           page_count=out.get("page_count"), artifact_sha256=out.get("artifact_sha256"), evidence_eligibility=out["evidence_eligibility"])
                if out["outcome"] == "PRODUCED":
                    with case.reader() as kb:
                        v = case.svc(kb).verify(artifact_id=out["artifact_id"])
                        row["anchors_verified"] = v["anchors_checked"] if v["valid"] else -1
                        if i in (0, 20, 40, 60, 68):
                            row["sample"] = case.svc(kb).show(artifact_id=out["artifact_id"], page=1)["pages"][0]
            rows.append(row)
        with case.reader() as kb:
            manifest = __import__("scivetra_kb.core.manifest", fromlist=["parse_manifest"]).parse_manifest(kb)
        from scivetra_kb.core.doctor import doctor
        report = doctor(case.root, full=True)
        return rows, manifest, report["problems"], report.get("parse_invariants")
    finally:
        case.tearDown()


def summarize(rows):
    s = {"n": len(rows), "intake": Counter(r["intake"] for r in rows), "parse": Counter(r.get("parse", "NOT_PARSED_INTAKE_REJECTED") for r in rows),
         "status": Counter(r["status"] for r in rows if r.get("status")), "scenario": Counter(r["scenario"] for r in rows),
         "intake_reject_reasons": Counter(x for r in rows for x in r["intake_reasons"]), "parse_reasons": Counter(x for r in rows for x in r.get("parse_reasons", [])),
         "identity_state_auto": Counter(str(r["identity_state_auto"]) for r in rows if r["intake"] == "REGISTERED"),
         "evidence_eligibility": Counter(r["evidence_eligibility"] for r in rows if r.get("parse") == "PRODUCED"),
         "anchors_verified": sum(r.get("anchors_verified", 0) for r in rows), "anchor_failures": sum(1 for r in rows if r.get("anchors_verified") == -1)}
    matrix = {}
    for r in rows:
        key = r["family"]
        matrix.setdefault(key, Counter())[r.get("status") or r.get("parse") or ("INTAKE_" + r["intake"])] += 1
    s["format_matrix"] = {k: dict(sorted(v.items())) for k, v in sorted(matrix.items())}
    return json.loads(json.dumps({k: (dict(sorted(v.items())) if isinstance(v, Counter) else v) for k, v in s.items()}))


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--out-dir", required=True)
    args = p.parse_args(argv)
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    first, m1, problems1, inv1 = build()
    second, m2, problems2, inv2 = build()
    strip = lambda rows: [{k: v for k, v in r.items()} for r in rows]  # noqa: E731
    s1, s2 = summarize(first), summarize(second)
    deterministic = strip(first) == strip(second) and m1 == m2
    produced = sum(1 for r in first if r.get("parse") == "PRODUCED")
    expected = {"n": 100, "intake_rejected": 6, "refused": 4, "failed": 4, "produced": 86}
    observed = {"n": len(first), "intake_rejected": s1["intake"].get("REJECTED", 0), "refused": s1["parse"].get("REFUSED", 0),
                "failed": s1["parse"].get("FAILED", 0), "produced": produced}
    summary = {"schema": "rkb-s06-pilot/1", "summary": s1, "expected": expected, "observed": observed, "accounting_ok": expected == observed,
               "builds_identical": deterministic, "parse_manifest_sha256": m1["manifest_sha256"], "doctor_problems": problems1 + problems2,
               "parse_invariants": inv1, "python": sys.version.split()[0], "platform": sys.platform,
               "note": "syntactic acceptance (intake) and parse status are NOT identity correctness; links were confirmed by a simulated human"}
    (out / "pilot_summary.json").write_text(json.dumps(summary, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    (out / "pilot_rows.json").write_text(json.dumps([{k: v for k, v in r.items() if k != "sample"} for r in first], indent=1, sort_keys=True) + "\n",
                                         encoding="utf-8")
    (out / "representative_anchors.json").write_text(json.dumps([{"doc": r["doc"], "family": r["family"], "artifact_sha256": r["artifact_sha256"],
                                                                  "page_1": r["sample"]} for r in first if "sample" in r], indent=1, sort_keys=True) + "\n",
                                                     encoding="utf-8")
    (out / "fixture_hashes.json").write_text(json.dumps({f"doc_{r['doc']:03d}.pdf": r["fixture_sha256"] for r in first}, indent=1, sort_keys=True) + "\n",
                                             encoding="utf-8")
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    statuses = sorted({k for v in s1["format_matrix"].values() for k in v})
    w.writerow(["family"] + statuses + ["total"])
    for fam, counts in s1["format_matrix"].items():
        w.writerow([fam] + [counts.get(k, 0) for k in statuses] + [sum(counts.values())])
    (out / "format_status_matrix.csv").write_text(buf.getvalue(), encoding="utf-8")
    ok = summary["accounting_ok"] and deterministic and not summary["doctor_problems"] and s1["anchor_failures"] == 0 and s1 == s2
    print(json.dumps({"ok": ok, "observed": observed, "builds_identical": deterministic, "anchors_verified": s1["anchors_verified"]}, sort_keys=True))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
