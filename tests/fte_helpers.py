def write_ta_release(directory, n, *, release_id="crl_fte_synthetic", doi_for=None, screening_sha=None, extra=None):
    """A synthetic screened Stage-11 portable export with the Stage-10 binding, and the matching native verify JSON."""
    items = []
    for i in range(n):
        dois = doi_for(i) if doi_for else [(f"10.99999/fte.{i}", f"10.99999/fte.{i}")]
        items.append(s03_item(f"cri_fte_{i:04d}", dois=dois, title=f"Synthetic full-text study number {i}", author="First Synthetic"))
    sem = hashlib.sha256(f"{release_id}:{n}".encode()).hexdigest()
    manifest_extra = {"project_revision_id": "rev_synthetic_s05", "screening_run_id": "scr_synthetic_s05",
                      "screening_manifest_sha256": screening_sha or hashlib.sha256(b"synthetic screening").hexdigest(),
                      "screen_include_count": n, "screen_exclude_count": 3, **(extra or {})}
    write_export(directory, items, release_id=release_id, release_semantic=sem, manifest_extra=manifest_extra)
    verify = str(Path(directory).parent / (Path(directory).name + "_native_verify.json"))
    Path(verify).write_text(json.dumps({"valid": True, "release_id": release_id, "release_manifest_sha256": sem, "corpus_item_count": n,
                                        "screen_include_count": n, "screen_exclude_count": 3, "file_count": 4,
                                        "scope": "synthetic stand-in for reprovane corpus verify-export output"}), encoding="utf-8")
    return items, sem, verify


def write_stage11b_export(directory, items, *, release_id, release_sem, acquired, run_id="ftr_rv_synthetic_11b", version="publishedVersion",
                          licence="cc-by", mutate=None):
    """KB-built synthetic RV-Stage11B portable export (NOT native; same five files, digests and rendering as Reprovane 2.0.1).

    ``acquired``: {corpus_item_id: selected artifact sha256}; every other item is MANUAL_REQUIRED. ``mutate(statuses)`` may
    alter item statuses before the digests are computed (consistent but wrong exports). Returns the manifest digest."""
    from tests.bridge_helpers import manual_row
    from scivetra_kb.bridge.sources import _render, rv_digest
    policy_sha = hashlib.sha256(b"synthetic fulltext policy").hexdigest()
    statuses = []
    for item in items:
        cid, art = item["corpus_item_id"], acquired.get(item["corpus_item_id"])
        cand = "ftc_" + hashlib.sha256(cid.encode()).hexdigest()[:12]
        statuses.append({"attempts": [{"candidate_id": cand, "ordinal": 0, "outcome": {"artifact_sha256": art, "failure_class": None, "status": "ACQUIRED"}}]
                         if art else [], "corpus_item_id": cid, "publication_entity_id": item["publication_entity_id"],
                         "reasons": [] if art else ["AUTH_REQUIRED"], "selected_artifact_sha256": art, "selected_candidate_id": cand if art else None,
                         "selected_evidence": [{"evidence_provider": "FROZEN", "is_oa": True, "license": licence, "url_type": "DIRECT_PDF",
                                                "version": version}] if art else [],
                         "status": "ACQUIRED_AUTO" if art else "MANUAL_REQUIRED"})
    if mutate:
        mutate(statuses)
    for st in statuses:
        st["status_sha256"] = rv_digest({k: v for k, v in st.items() if k != "status_sha256"})
    by_id = {i["corpus_item_id"]: i for i in items}
    queue = [manual_row(by_id[cid], release_id, release_sem, policy_sha)
             for cid in sorted(st["corpus_item_id"] for st in statuses if st["status"] != "ACQUIRED_AUTO")]
    artifacts = {a["outcome"]["artifact_sha256"] for st in statuses for a in st["attempts"] if a["outcome"]["status"] == "ACQUIRED"}
    manifest = {"artifact_count": len(artifacts), "budget": {"artifacts": len(artifacts)}, "evidence_inventory": [], "failure_count": len(queue),
                "fulltext_policy": {"synthetic": True}, "fulltext_policy_sha256": policy_sha, "handoff_sha256": "0" * 64,
                "interpretation": "synthetic KB-built Stage-11B fixture", "items": statuses, "manual_queue": queue, "manual_queue_sha256": rv_digest(queue),
                "ordered_corpus_item_ids": [st["corpus_item_id"] for st in statuses], "provider_lookup_evidence": [], "release_id": release_id,
                "release_manifest_sha256": release_sem, "run_id": run_id, "schema": "fulltext-manifest/1"}
    os.makedirs(directory, exist_ok=True)
    for name, body in _render(manifest).items():
        Path(directory, name).write_bytes(body)
    return rv_digest(manifest)


class FTECase(KBTest):
    def setUp(self):
        super().setUp()
        self.fixtures = os.path.join(self.tmp, "fixture-root")
        os.makedirs(self.fixtures)
        self.titles = {}

    def make_run(self, n=6, *, roster=None, protocol=None, label="synthetic FTE run", workspace="ws", doi_for=None, release_id="crl_fte_synthetic"):
        export = os.path.join(self.tmp, f"rv_{release_id}")
        items, sem, verify = write_ta_release(export, n, release_id=release_id, doi_for=doi_for)
        with self.writer() as kb:
            imported = LibraryService(kb).import_release(export, workspace_label=workspace, operator="op.lib")
            source = kb.one("SELECT release_import_id FROM reprovane_release_import WHERE release_manifest_sha256=?", (sem,))["release_import_id"]
            svc = FTEService(kb)
            protocol_id = svc.create_protocol(copy.deepcopy(protocol or PROTOCOL), operator="op.fte")["protocol_id"]
            run = svc.create_run(source_id=source, export_dir=export, expected_manifest_sha256=sem, rv_verify_json=verify, protocol_id=protocol_id,
                                 roster=copy.deepcopy(roster or ROSTER), label=label, operator="op.fte")
            candidates = svc.candidates(run["run_id"])
        for i, it in enumerate(items):
            self.titles[it["corpus_item_id"]] = f"Synthetic full-text study number {i}"
        return {"run_id": run["run_id"], "run": run, "candidates": candidates, "source": source, "export": export, "sem": sem, "verify": verify,
                "protocol_id": protocol_id, "items": items, "imported": imported}

    def add_pdf(self, candidate, *, version="PUBLISHED", confirm=True, rights="OPEN", variant="", paper_id=None):
        """Verified KB PDF for the candidate's paper: document version, G0-G3 intake, optional human CONFIRM, rights assessment."""
        title = self.titles.get(candidate["corpus_item_id"], "Synthetic")
        name = f"{candidate['corpus_item_id']}_{version}_{variant}.pdf"
        Path(self.fixtures, name).write_bytes(synthetic_pdf([title_page(title=title, authors=["First Synthetic"], doi="10.99999/fte.x",
                                                                         body=[f"Synthetic body {variant} {version}"])]))
        with self.writer() as kb:
            svc = AssetService(kb)
            dv = svc.add_document_version(paper_id=paper_id or candidate["paper_id"], version_class=version, evidence=VERSION_EVIDENCE[version],
                                          operator="op.lib")["document_version_id"]
            out = svc.register_asset(fixture_root=self.fixtures, relative_path=name, document_version_id=dv, operator="op.lib")
            if confirm:
                svc.review_link(link_id=out["link_id"], decision="CONFIRM", operator="op.lib", reason="title page checked by a human")
            if rights == "OPEN":
                svc.assess_rights(asset_sha256=out["asset_sha256"], document_version_id=dv, operator="op.lib",
                                  evidence=RIGHTS.get(version, RIGHTS["PUBLISHED"]))
            elif rights == "RESTRICTED":
                svc.assess_rights(asset_sha256=out["asset_sha256"], document_version_id=dv, operator="op.lib", evidence=RESTRICTED)
        return {"link_id": out["link_id"], "asset_sha256": out["asset_sha256"], "document_version_id": dv}

    def svc_call(self, method, **kw):
        with self.writer() as kb:
            return getattr(FTEService(kb), method)(**kw)

    def attach(self, candidate, **kw):
        ev = self.add_pdf(candidate, **kw)
        return self.svc_call("attach_kb_asset", candidate_id=candidate["candidate_id"], link_id=ev["link_id"], operator="op.fte"), ev

    def both(self, candidate, outcome, reasons=(), **kw):
        a = self.svc_call("decide", candidate_id=candidate["candidate_id"], reviewer="rev.a", outcome=outcome, reasons=list(reasons), **kw)
        b = self.svc_call("decide", candidate_id=candidate["candidate_id"], reviewer="rev.b", outcome=outcome, reasons=list(reasons), **kw)
        return a, b

    def attempts(self, candidate, n=2, status="LOGIN_REQUIRED"):
        for k in range(n):
            self.svc_call("record_attempt", candidate_id=candidate["candidate_id"], status=status, source_description=f"publisher landing page try {k}",
                          attempted_on=f"2026-10-{10 + k:02d}", operator="op.acq")


